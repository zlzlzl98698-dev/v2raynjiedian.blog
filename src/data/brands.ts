export function getBrandBySlug(slug: string): Brand | undefined {
  return brandsData.find((b) => b.slug === slug);
}

export function getPrimaryBrand(): Brand {
  return brandsData.find((b) => b.isPrimarySponsored) || brandsData[0];
}

export function getTopBrands(limit = 10): Brand[] {
  return [...brandsData].sort((a, b) => a.rank - b.rank).slice(0, limit);
}
